guide='''# ПОГРУЗЧИК: как начать

## 1. Открой симулятор

Открой Open_Simulation_3D.html в Chrome или Edge. Интернет не нужен.

## 2. Настрой поле

Измерь настоящее поле рулеткой. Нажми **«Размеры на карте»**, затем нужное число. Введи размер в миллиметрах и сохрани. **«Линейка»** измеряет расстояние между двумя точками на экране.

## 3. Выбери задание

В панели справа выбери стартовый круг и направление робота. Нажми **«Где груз»** и укажи его зону. Затем **«Куда везти»** — зону во втором круге.

Гантель лежит — лапы внизу. Стоит — переставь те же лапы в верхние отверстия. Каждая лапа держится на двух боковых винтах М3×16 с потайной головкой. Они вкручиваются изнутри наружу прямо в пластик.

## 4. Проверь заезд

Нажми **«Проверка»**: можно поднять и опустить вилы, поставить перед ними груз, проехать и повернуть. Движение останавливается через заданное время. **«Стоп»** останавливает колёса и удерживает вилы. Для автоматического заезда нажми **«Заезд заново»**.

После прямой пробы введи реальный путь, после поворота — реальный угол. **«Применить поправку модели»** подгонит скорость или поворот. На настоящем роботе используй те же PWM и время. Эти поправки меняют только симуляцию.

Нажми **«Запустить»**. Есть пауза, ускорение и шаг по 0,1 секунды. Если груз не доставлен, проверь положение лап и время движений в настройках.

Обзор: левая кнопка мыши — вращать; зажатое колесо — сдвигать; колесо — приближать. **«К роботу»** включает слежение.

## 5. Сохрани результат

Нажми **«↓ HTML»**. Получится один файл с полем и всеми настройками. Его можно открыть на другом компьютере. Без сохранения изменения пропадут после закрытия страницы.

## 6. Запиши программу в Arduino

Нужна **UNO или классическая Nano на ATmega328P, 16 МГц**. Отключи питание моторов и подключи USB. Во вкладке **Arduino** выбери свою плату. Для неизвестной Nano выбери **«Nano · не знаю загрузчик»**. Нажми **«Записать программу по USB»**, выбери порт и дождись окончания. Если USB недоступен, открой файл в отдельном Chrome или Edge.

## 7. Настрой настоящего робота

Кнопки во вкладке **«Проверка»** управляют виртуальным роботом. Во вкладке **Arduino** есть отдельные кнопки для настоящей платы по USB: поднять, опустить, короткие движения и стоп. Для движения сними груз, опусти вилы, нажми **«Разрешить пробы»**. При отключении USB не рассчитывай на кнопку сайта: моторная проба ограничена двумя секундами.

Во вкладке Arduino нажми **«Подключить»**. Дождись **RADIAL READY**. Поставь все три датчика над белым покрытием, нажми **«Белое»** и дождись **CAL SAMPLE OK**. Повтори для чёрного и обоих кругов. Нажми **«Сохранить»**.

Поставь робота в центр выбранного круга, направь как в симуляции. Вилы опусти. Удерживай кнопку старта 2 секунды, отпусти, затем коротко нажми и отпусти ещё раз. Нажатие во время заезда останавливает колёса. В USB `status` для кнопки на A3 должно быть `start_raw=1` в покое и `start_raw=0` при нажатии. Датчик HW-511 на D2 по умолчанию считает отражающий груз при HIGH и не использует внутреннюю подтяжку Arduino. Проверь `contact_raw` и `contact`: без груза должно быть `contact=0`, с грузом `contact=1`. Если наоборот, введи `contact low` (или `contact high`). Для модуля без собственной подтяжки есть `contact pullup on`, для возврата `contact pullup off`; настройки сохраняются.

**Важно:** размеры поля не меняют время движений автоматически. Проверь его на роботе. Симуляция не проверяет прочность и пробуксовку. USB-загрузчик пока испытан только на программной модели платы.
'''
