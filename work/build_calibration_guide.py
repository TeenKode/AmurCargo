from pathlib import Path
import html,re
R=Path(__file__).resolve().parents[1];O=R/'outputs/AmurCargo_Radial'
guide='''# Как подогнать симуляцию под робота

**Правило: меняй одну настройку за раз. Каждый замер повторяй трижды и бери среднее.** Настраивай на одном покрытии, с тем же грузом и одинаково заряженной батареей.

## 1. Сначала размеры

Введи размеры поля через «Размеры на карте». В «Настройки → Модель поля и робота» укажи расстояние между центрами колёс, положение и расстояние между датчиками. Всё — в миллиметрах.

## 2. Настрой датчики

Во вкладке Arduino измерь белое, чёрное и оба круга. Сохрани. Нажми «Поток»: робот покажет значения после line=. В модели поставь похожие средние значения для зелёного и голубого кругов.

Для шума смотри на неподвижный робот над кругом: если показания меняются от 480 до 520, поставь «Шум датчиков» = 20. Если покрытия почти не различаются, сначала исправь подсветку и высоту датчиков.

## 3. Совмести скорость без груза

Быстрый способ: открой **«Проверка»**, задай PWM и время, нажми **«Вперёд»**. Повтори на настоящем роботе через Arduino → Подключить → Разрешить пробы. Вилы внизу, груз снят. Измеряй смещение оси колёс от старта до полной остановки. Введи средний результат трёх проб и нажми **«Применить поправку модели»**.

На прямом луче отметь сбоку участок 100 мм. Засеки время, за которое ось колёс проходит его после разгона. Сравни с таким же участком в симуляции. Скорости моторов в программе должны быть одинаковыми для обоих заездов.

Исправь «Скорость колеса при PWM 255» по правилу: **новая скорость = старая × время в модели ÷ время в реальности**.

Пример: в модели 1 с, в жизни 1,25 с. Было 300 — поставь **240 мм/с**. PWM — число, которым программа задаёт мощность мотора; здесь оно нужно только для названия настройки.

## 4. Совмести уход в сторону

Если настоящий робот уходит влево, а модель едет прямо, уменьшай «Отдача левого мотора» на 0,01–0,02. Если уходит вправо — уменьшай правую. Добейся похожего изгиба пути. Пока не меняй одновременно поправки моторов в программе. Затем снова проверь скорость.

## 5. Проверь движение с грузом

Повтори замер прямого участка с грузом. Меняй только **«Скорость с грузом: множитель»** по тому же правилу времени. Например, 1 с в модели и 1,25 с в жизни: множитель 1 → 0,8.

## 6. Совмести повороты

В **«Проверка»** нажми **«Влево»** или **«Вправо»**. Измерь реальный угол за те же PWM и время. Введи его положительное значение и примени поправку модели. Для пробы с грузом используй результат реального заезда: короткие USB-пробы моторов с грузом прошивка не разрешает.

Сними одинаковый поворот робота и модели, например на 90°. Сравни угол за одинаковое время. Если модель делает 90°, а робот 80°, умножь **«Поворот на месте: множитель»** на 80 ÷ 90. При значении 1 получится примерно **0,89**.

Повтори с грузом. Для этой проверки меняй только **«Поворот с грузом: множитель»**. Размер между колёсами оставь измеренным — не исправляй им ошибки поворота.

## 7. Теперь настрой саму программу

Когда модель движется похоже, подбери время поворота, выезда из круга, возврата к центру и разгрузки. Проверь сначала один луч, затем переезд во второй круг. После изменения настроек программы запиши их в Arduino и сравни заезды снова.

Для поворота меняй время небольшими шагами, например по 10–20 мс. 1000 мс = 1 секунда. Параметры модели меняют только симуляцию; настройки программы применяются и в симуляции, и в роботе.

## 8. Проведи итоговую проверку

Сделай три одинаковых заезда с грузом. Затем проверь другие зоны. Начальная цель: разница до 10 мм на прямом участке 300 мм и до 5° на повороте. Это цель настройки, а не обещание точности.

Совпало — нажми **«↓ HTML»**. Изменились батарея, покрытие или масса груза — повтори замеры скорости и поворота.

**Предел модели:** она не рассчитывает силы, неровности и прочность. Без датчиков оборотов колёс точное совпадение не гарантируется. Финальная проверка всегда на настоящем поле.
'''
